/*

As diferenças entre JVM, JRE e JDK:

JVM (Java Virtual Machine) - é a Máquina Virtual do Java
responsável por executar o bytecode;

JRE (Java Runtime Environment) - Ambiente de Execução do Java
que fornece as bibliotecas padrões do Java para o JDK compilar
o seu código e para a JVM executar o seu programa;

JDK (Java Development Kit) - Kit de Desenvolvimento Java
responsável por compilar código-fonte em bytecode.

*/